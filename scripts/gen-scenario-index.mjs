#!/usr/bin/env node
/**
 * Generates docs/scenarios/README.md from scenarios/<name>/README.md and
 * scenarios/<name>/expected-checks.json. test/scenario-index.test.js fails when
 * the committed index is stale.
 *
 *   node scripts/gen-scenario-index.mjs           write docs/scenarios/README.md
 *   node scripts/gen-scenario-index.mjs --check   exit 1 if the committed file is stale
 *
 * test/scenario-index.test.js runs the same comparison under `npm test`.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const INDEX_PATH = path.join(REPO_ROOT, 'docs', 'scenarios', 'README.md');

function readScenario(scenariosDir, name) {
  const readme = fs.readFileSync(path.join(scenariosDir, name, 'README.md'), 'utf-8');
  const expected = JSON.parse(fs.readFileSync(path.join(scenariosDir, name, 'expected-checks.json'), 'utf-8'));
  // Bold "**Label:** value" fields, alone on a line or separated by " | ".
  const field = label => readme.match(new RegExp(`\\*\\*${label}:\\*\\*\\s+([^|\\n]+)`))?.[1].trim() ?? null;
  return {
    name,
    title: readme.match(/^#\s+(.+)$/m)?.[1].trim() ?? name,
    severity: field('Severity'),
    autoFix: field('Auto-Fix'),
    expected,
  };
}

// The HackMyAgent version this package installs, from the lockfile.
function hmaVersion(root) {
  const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf-8'));
  return lock.packages?.['node_modules/hackmyagent']?.version ?? 'unknown';
}

const cell = value => String(value ?? '-').replace(/\|/g, '\\|');
// "Yes", "No" or "No (manual)" in the README; "-" when the README does not say.
const autoFix = value => (value ? value.split(/\s+/)[0] : '-');

export function renderIndex(root = REPO_ROOT) {
  const scenariosDir = path.join(root, 'scenarios');
  const scenarios = fs.readdirSync(scenariosDir, { withFileTypes: true })
    .filter(e => e.isDirectory() && e.name !== 'examples')
    .map(e => readScenario(scenariosDir, e.name))
    .sort((a, b) => a.name.localeCompare(b.name));
  const detected = scenarios.filter(s => s.expected.length > 0);
  const undetected = scenarios.filter(s => s.expected.length === 0);

  return [
    '# DVAA scenarios',
    '',
    '<!-- Generated by scripts/gen-scenario-index.mjs from scenarios/*/README.md and expected-checks.json. Do not edit by hand: run `node scripts/gen-scenario-index.mjs`. -->',
    '',
    'A scenario in `scenarios/<name>/` consists of a deliberately vulnerable fixture in `vulnerable/`, a README that explains the attack, and an `expected-checks.json` listing the HackMyAgent checks that should fire on the fixture.',
    '',
    `${scenarios.length} scenarios: ${detected.length} have expected checks, baselined against HackMyAgent ${hmaVersion(root)} (static scan); ${undetected.length} have none yet, and their README explains the detection status.`,
    '',
    '```bash',
    '# Scan a scenario and compare the findings with its expected checks',
    'dvaa scan llm-exposed-ollama',
    '',
    "# Apply HackMyAgent's fixes to a temporary copy and show what changed (the fixture is not modified)",
    'dvaa scan llm-exposed-ollama --fix',
    '',
    '# Detect, fix and re-scan every scenario that has expected checks',
    'scenarios/verify-all.sh',
    '```',
    '',
    `## Scenarios with expected checks (${detected.length})`,
    '',
    '| Scenario | Expected checks | Severity | Auto-fix | Title |',
    '|----------|-----------------|----------|----------|-------|',
    ...detected.map(s => `| \`${s.name}\` | ${s.expected.join(', ')} | ${cell(s.severity)} | ${autoFix(s.autoFix)} | ${cell(s.title)} |`),
    '',
    `## Scenarios without static detection (${undetected.length})`,
    '',
    "Their `expected-checks.json` is `[]`. Each README's Detection status section explains what is missing.",
    '',
    '| Scenario | Severity | Title |',
    '|----------|----------|-------|',
    ...undetected.map(s => `| \`${s.name}\` | ${cell(s.severity)} | ${cell(s.title)} |`),
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const text = renderIndex();
  const relPath = path.relative(REPO_ROOT, INDEX_PATH);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(INDEX_PATH) ? fs.readFileSync(INDEX_PATH, 'utf-8') : '';
    if (current !== text) {
      console.error(`${relPath} is stale. Run: node scripts/gen-scenario-index.mjs`);
      process.exit(1);
    }
    console.log(`${relPath} is up to date.`);
  } else {
    fs.writeFileSync(INDEX_PATH, text);
    console.log(`Wrote ${relPath}`);
  }
}
